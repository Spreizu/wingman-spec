'use strict';
/**
 * anchorguard.cjs - is an `@spec` anchor still about the code it sits on? Package-managed (overwritten by install.sh).
 * Plain Node >= 18, no dependencies, language-agnostic (line heuristics from placement.cjs, no parsers), nothing stored:
 * every answer comes from the files, `git diff` against a base, and `git blame`/`git log` at check time.
 *
 *   analyze(text)                 the anchored unit of every marker: whole function (marker in its doc comment) or the
 *                                 lines directly below a marker. A unit's "body" ignores blank lines, comments and spacing.
 *   compareAnchors(base, cur)     per marker: modified | added | removed (body text differs, new, gone)
 *   guard({...})                  change-time findings from the diff of a change/task against its base:
 *                                 anchor-touched-unlisted, requirement-changed-code-untouched, anchor-removed, anchor-moved,
 *                                 anchor-sprawl, anchor-outside-task-files
 *   testEvidence(output, scenarios)  did the tests tagged for each scenario appear PASSING in the test runner output
 *   staleAnchors({...})           outside a change: a unit changed in a commit later than the requirement text (git blame)
 *
 * Every check warns by default and is built to stay quiet on normal work: formatting, comment edits, edits to another
 * function of the same file, files without markers, generated/vendored files. It cannot judge whether a requirement
 * is semantically still true: that stays with the independent reviewer and the tests.
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { MARKER_LEADER, KEY, isUnitStart, COMMENT_LINE, ANNOTATION, CLOSING } = require('./placement.cjs');

const GENERATED_DIR = /(^|\/)(generated|__generated__|vendor|vendored|third[_-]party|dist)(\/|$)/;
const GENERATED_HEAD = /@generated|DO NOT EDIT|auto-?generated|code generated by/i;
const isGenerated = (file, text) => GENERATED_DIR.test(file) || GENERATED_HEAD.test(String(text || '').split('\n').slice(0, 5).join('\n'));
const SPRAWL = { anchors: 6, files: 3 };

const indentOf = (l) => (l.match(/^\s*/)[0] || '').replace(/\t/g, '    ').length;
const normLine = (l) => l.replace(/\s+(?:\/\/+|#+)(?:\s.*)?$/, '').replace(/\s+/g, ' ').trim();
const stripStrings = (l) => l.replace(/\\./g, '').replace(/'[^']*'|"[^"]*"|`[^`]*`/g, '""').replace(/\s\/\/.*$/, '');

/** Keys of the markers on one line. */
function keysOf(l) {
  const m = MARKER_LEADER.exec(l); if (!m) return [];
  const keys = []; let rest = l.slice(m.index + m[0].length), k;
  while ((k = rest.match(KEY))) { keys.push(`${k[1]}/${k[2]}`); rest = rest.slice(k[0].length); }
  return keys;
}

/** The anchored unit of every marker of one text: [{ key, line (1-based marker line), start, end (0-based, inclusive), whole, header, body }]. */
function analyze(text) {
  const lines = String(text).replace(/\r\n/g, '\n').split('\n'); const out = [];
  if (!/@spec\b/.test(text)) return out;
  const docLine = []; let inDoc = false;
  lines.forEach((l, i) => { const q = (l.match(/"""|'''/g) || []).length; docLine[i] = inDoc || q % 2 === 1; if (q % 2 === 1) inDoc = !inDoc; });
  const isComment = (i) => COMMENT_LINE.test(lines[i]) || docLine[i];
  const starts = []; lines.forEach((l, i) => { if (!isComment(i) && isUnitStart(l)) starts.push(i); });
  const endCache = new Map();
  const unitEnd = (s) => {
    if (endCache.has(s)) return endCache.get(s);
    let brace = -1;
    if (!/:\s*$/.test(lines[s])) for (let j = s; j < Math.min(lines.length, s + 3); j++) { if (isComment(j)) continue; if (lines[j].includes('{')) { brace = j; break; } if (/;\s*$/.test(lines[j]) || (j > s && isUnitStart(lines[j]))) break; }
    let end = s;
    if (brace >= 0) {
      let depth = 0, seen = false; end = lines.length - 1;
      for (let j = brace; j < lines.length; j++) {
        if (isComment(j)) continue; const t = stripStrings(lines[j]);
        for (const ch of t) { if (ch === '{') { depth++; seen = true; } else if (ch === '}') depth--; }
        if (seen && depth <= 0) { end = j; break; }
      }
    } else {
      const ind = indentOf(lines[s]);
      for (let j = s + 1; j < lines.length; j++) {
        if (!/\S/.test(lines[j])) continue;
        if (indentOf(lines[j]) > ind || (isComment(j) && indentOf(lines[j]) >= ind)) { end = j; continue; }
        if (indentOf(lines[j]) === ind && /^\s*end\b/.test(lines[j])) end = j;
        break;
      }
    }
    endCache.set(s, end); return end;
  };
  const bodyOf = (a, b) => { const o = []; for (let j = a; j <= b && j < lines.length; j++) { if (!/\S/.test(lines[j]) || isComment(j)) continue; const n = normLine(lines[j]); if (n) o.push(n); } return o.join('\n'); };
  lines.forEach((l, i) => {
    const keys = keysOf(l); if (!keys.length) return;
    let start = -1, end = -1, whole = false, header = '';
    let enclosing = -1; for (const s of starts) if (s <= i && unitEnd(s) >= i) enclosing = s;
    if (docLine[i] && enclosing >= 0 && enclosing < i) { start = enclosing; end = unitEnd(enclosing); whole = true; }
    else {
      let j = i + 1; while (j < lines.length && (COMMENT_LINE.test(lines[j]) || ANNOTATION.test(lines[j]) || docLine[j])) j++;
      if (j < lines.length && starts.includes(j) && /\S/.test(lines[j]) && !/\S/.test(l.slice(0, MARKER_LEADER.exec(l).index).replace(/\/\*+|\*+/g, ''))) { start = j; end = unitEnd(j); whole = true; }
    }
    if (whole) header = normLine(lines[start]);
    else {
      const ind = indentOf(l); start = i + 1; end = i; header = enclosing >= 0 ? normLine(lines[enclosing]) : '';
      const inline = /\S/.test(l.slice(0, MARKER_LEADER.exec(l).index).replace(/\/\*+|\*+/g, ''));
      if (inline) { start = i; end = i; }
      else for (let j = i + 1; j < lines.length; j++) { if (!/\S/.test(lines[j]) || CLOSING.test(lines[j]) || indentOf(lines[j]) < ind || keysOf(lines[j]).length) break; end = j; }
      if (end < start) { start = i; end = i; }
    }
    for (const key of keys) out.push({ key, line: i + 1, start, end, whole, header, body: bodyOf(start, end) });
  });
  return out;
}

/** Marker-level differences between two versions of one file: [{ kind: modified|added|removed, key, line, header, whole }]. */
function compareAnchors(baseText, curText) {
  const A = analyze(baseText || ''), B = analyze(curText || '');
  const id = (u) => `${u.key}|${u.whole ? 'U' : 'P'}|${u.header}`;
  const group = (xs) => { const m = new Map(); for (const u of xs) { const k = id(u); if (!m.has(k)) m.set(k, []); m.get(k).push(u); } return m; };
  const ga = group(A), gb = group(B); const ev = []; const loseA = [], loseB = [];
  for (const [k, bs] of gb) { const as = ga.get(k) || []; bs.forEach((b, i) => { if (as[i]) { if (as[i].body !== b.body) ev.push({ kind: 'modified', key: b.key, line: b.line, header: b.header, whole: b.whole }); } else loseB.push(b); }); }
  for (const [k, as] of ga) { const bs = gb.get(k) || []; as.forEach((a, i) => { if (!bs[i]) loseA.push(a); }); }
  for (const b of loseB) {
    const j = loseA.findIndex((a) => a.key === b.key);
    if (j >= 0) { loseA.splice(j, 1); ev.push({ kind: 'modified', key: b.key, line: b.line, header: b.header, whole: b.whole, renamed: true }); }
    else ev.push({ kind: 'added', key: b.key, line: b.line, header: b.header, whole: b.whole, body: b.body });
  }
  for (const a of loseA) ev.push({ kind: 'removed', key: a.key, line: a.line, header: a.header, whole: a.whole, body: a.body });
  return ev;
}

// ---------- git ----------
function git(cwd, args, max) { const r = spawnSync('git', args, { cwd, encoding: 'utf8', maxBuffer: max || 64 * 1024 * 1024 }); return r.status === 0 ? r.stdout : null; }
const isRepo = (cwd) => git(cwd, ['rev-parse', '--git-dir']) !== null;
const readIf = (f) => { try { return fs.readFileSync(f, 'utf8'); } catch (e) { return null; } };

/** Files changed since `base` (committed or not, plus untracked): [{ file, from }] (from: the old path of a rename). */
function changedSince(codeRoot, base) {
  const out = new Map();
  const ns = git(codeRoot, ['diff', '--name-status', '-M', base, '--']); if (ns === null) return null;
  for (const l of ns.split('\n').filter(Boolean)) { const p = l.split('\t'); const st = p[0][0]; if (st === 'R' || st === 'C') out.set(p[2], { file: p[2], from: p[1] }); else out.set(p[1], { file: p[1], from: p[1] }); }
  const un = git(codeRoot, ['ls-files', '--others', '--exclude-standard']) || '';
  for (const f of un.split('\n').filter(Boolean)) if (!out.has(f)) out.set(f, { file: f, from: null });
  return [...out.values()];
}

/**
 * Change-time findings. opts: { codeRoot, base, listed:Set, reviewed:Set, modifiedKeys:Set (MODIFIED in the delta), removedKeys:Set,
 *   mineKeys:Set|null (requirements to check for sprawl; null = all), manyKeys:Set (requirements that say `Anchors: many`: no sprawl finding), markers:[{key,file,line,test}] (current), isTest(file), taskFiles:[]|null, only:[files]|null }
 * Returns { findings: [{ kind, key, file, line, text }], touched:Set(keys), files:[files with anchor events] }.
 */
function guard(o) {
  const findings = []; const touched = new Set(); const eventFiles = new Set(); const add = (kind, key, file, line, text) => findings.push({ kind, key, file, line, text });
  const listed = o.listed || new Set(), reviewed = o.reviewed || new Set();
  const changed = o.base ? changedSince(o.codeRoot, o.base) : null;
  const code = (o.markers || []).filter((m) => !m.test && !isGenerated(m.file, ''));
  const events = [];
  if (changed) for (const c of changed) {
    if (o.only && !o.only.includes(c.file)) continue;
    if (o.isTest && o.isTest(c.file)) continue;
    if (/^openspec\//.test(c.file) || GENERATED_DIR.test(c.file)) continue;
    const baseText = c.from ? git(o.codeRoot, ['show', `${o.base}:${c.from}`]) : null;
    const curText = readIf(path.join(o.codeRoot, c.file));
    if ((baseText && baseText.includes('\0')) || (curText && curText.includes('\0'))) continue;
    if (isGenerated(c.file, curText || baseText)) continue;
    if (!(baseText || '').includes('@spec') && !(curText || '').includes('@spec')) continue;
    const curCode = (curText || '').split('\n').filter((l) => /\S/.test(l) && !COMMENT_LINE.test(l)).map(normLine).filter(Boolean).join('\n');
    for (const e of compareAnchors(baseText, curText)) events.push({ ...e, file: c.file, markerOnly: e.kind === 'removed' && !!e.body && curCode.includes(e.body) }); // markerOnly: the code is still there, only its marker is gone
  }
  // a unit that left one file and appeared in another: unchanged text = moved, different text = moved and edited
  for (const a of events.filter((e) => e.kind === 'added')) {
    const j = events.findIndex((e) => e.kind === 'removed' && e.key === a.key);
    if (j < 0) continue;
    const r = events[j]; events.splice(j, 1);
    if (r.body === a.body) { a.kind = 'moved'; a.from = r.file; } else { a.kind = 'modified'; a.movedFrom = r.file; }
  }
  const stillAnchored = (key) => code.some((m) => m.key === key);
  for (const e of events) {
    eventFiles.add(e.file);
    if (e.kind === 'modified' || e.kind === 'added') touched.add(e.key);
  }
  for (const e of events) {
    const where = `${e.file}:${e.line}`; const unit = e.header ? ` (\`${e.header.slice(0, 80)}\`)` : '';
    if ((e.kind === 'modified' || e.kind === 'added') && !listed.has(e.key) && !reviewed.has(e.key)) {
      const rename = e.renamed ? ' It was renamed or its signature changed.' : '';
      add('anchor-touched-unlisted', e.key, e.file, e.line, `${where}: code anchored to \`${e.key}\`${unit} ${e.kind === 'added' ? 'got a new anchor' : 'was modified'}, but this change does not mention that requirement (no delta, no \`Spec:\` line).${rename} Update the requirement and its scenarios (delta spec), or confirm it still holds with a line \`Reviewed anchors: ${e.key} - <why it still holds>\` in tasks.md or progress.md.`);
    }
    if (e.kind === 'moved' && !listed.has(e.key) && !reviewed.has(e.key)) add('anchor-moved', e.key, e.file, e.line, `${where}: the anchored unit of \`${e.key}\`${unit} moved here from ${e.from} unchanged. Confirm the anchor still belongs where it is now (and that the requirement does not describe the old place).`);
    if (e.kind === 'removed' && !o.removedKeys?.has(e.key)) {
      if (stillAnchored(e.key) && e.markerOnly) continue; // an extra marker was taken off (anchors prune): the requirement keeps its anchor and the code did not move
      if (stillAnchored(e.key)) { if (!listed.has(e.key) && !reviewed.has(e.key)) add('anchor-moved', e.key, e.file, e.line, `${where}: the anchored unit of \`${e.key}\`${unit} left this file; the requirement is still anchored in ${code.filter((m) => m.key === e.key).map((m) => m.file)[0]}. Confirm the anchor still belongs where it is now.`); }
      else if (!reviewed.has(e.key)) add('anchor-removed', e.key, e.file, e.line, `${where}: the anchored unit of \`${e.key}\`${unit} was removed or lost its marker and the requirement has no code anchor now. Restore or re-anchor it, or retire the requirement in a delta (REMOVED).`);
    }
  }
  if (o.modifiedKeys) for (const k of o.modifiedKeys) {
    if (reviewed.has(k) || touched.has(k) || !stillAnchored(k)) continue;
    const m = code.find((x) => x.key === k);
    add('requirement-changed-code-untouched', k, m.file, m.line, `${m.file}:${m.line}: requirement \`${k}\` is modified by the delta spec but none of the code anchored to it changed. Change the code, or add \`Reviewed anchors: ${k} - <why the code already satisfies the new text>\`.`);
  }
  // sprawl: one requirement spread over many places is not anchored at its entry point
  const per = new Map();
  for (const m of code) { if ((o.mineKeys && !o.mineKeys.has(m.key)) || (o.manyKeys && o.manyKeys.has(m.key))) continue; if (!per.has(m.key)) per.set(m.key, { n: 0, files: new Set() }); const p = per.get(m.key); p.n++; p.files.add(m.file); }
  for (const [k, p] of per) if (p.n > SPRAWL.anchors && p.files.size > SPRAWL.files) { const f = [...p.files][0]; add('anchor-sprawl', k, f, 0, `\`${k}\` has ${p.n} code anchors in ${p.files.size} files (more than ${SPRAWL.anchors} anchors in more than ${SPRAWL.files} files): spread too thin to mean anything. Anchor the entry point (the function that starts the behaviour) and let the tests cover the rest.`); }
  // anchors added or changed in files the task did not plan to touch
  if (o.taskFiles && o.taskFiles.length) {
    const ok = (f) => o.taskFiles.some((p) => p === f || (p.endsWith('/') && f.startsWith(p)) || (p.includes('*') && new RegExp(`^${p.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*\*/g, '\u0000').replace(/\*/g, '[^/]*').replace(/\u0000/g, '.*')}$`).test(f)) || f.startsWith(p.replace(/\/?$/, '/')));
    const seen = new Set();
    for (const e of events) if ((e.kind === 'modified' || e.kind === 'added') && !ok(e.file) && !seen.has(e.file)) { seen.add(e.file); add('anchor-outside-task-files', e.key, e.file, e.line, `${e.file}:${e.line}: a \`@spec\` anchor was ${e.kind === 'added' ? 'added' : 'changed'} in a file this task's \`Files:\` line does not list. Either the plan missed this file (name it) or the anchor is misplaced.`); }
  }
  return { findings, touched, files: [...eventFiles], events };
}

// ---------- test evidence ----------
const FAIL_LINE = /^\s*(?:not ok\b|[✗✖✕×]|FAIL(?:ED)?\b|--- FAIL\b|\[?FAILED\]?\b|\d+\)\s)/;
const PASS_LINE = /^\s*(?:ok\b|[✓✔]|PASS(?:ED)?\b|--- PASS\b|\[?PASSED\]?\b)/;
const SKIP_LINE = /#\s*(?:SKIP|TODO)\b|\bskipped\b|^\s*[○↓-]\s|^\s*--- SKIP\b|\bSKIPPED\b/i;
/**
 * `scenarios`: [{ id, requirement (key) }]; `output`: the test runner's output. Per scenario: 'passed' (a line with its tag looks like a
 * passing test), 'failed' (a failing/skipped line names it), 'unlisted' (the output never names it: quiet reporter).
 * Returns { byScenario: Map id -> state, byRequirement: Map key -> { passed, failed, unlisted } (scenario ids) }.
 */
function testEvidence(output, scenarios) {
  const lines = String(output || '').split('\n'); const byScenario = new Map(); const byRequirement = new Map();
  for (const s of scenarios) {
    const tag = `[${s.id}]`; let pass = 0, fail = 0;
    for (const l of lines) {
      if (!l.includes(tag)) continue;
      if (SKIP_LINE.test(l) || FAIL_LINE.test(l)) fail++; else if (PASS_LINE.test(l)) pass++;
    }
    const st = fail ? 'failed' : pass ? 'passed' : 'unlisted'; byScenario.set(s.id, st);
    if (!byRequirement.has(s.requirement)) byRequirement.set(s.requirement, { passed: [], failed: [], unlisted: [] });
    byRequirement.get(s.requirement)[st].push(s.id);
  }
  return { byScenario, byRequirement };
}

// ---------- stale anchors (git history only) ----------
/** Lines of a spec file that belong to the requirement starting at 1-based `line`: until the next `##`/`###` heading. */
function specRange(text, line) {
  const lines = String(text).split('\n'); let end = line;
  for (let i = line; i < lines.length; i++) { if (/^#{2,3}\s/.test(lines[i])) break; end = i + 1; }
  return [line, end];
}
/** `copies`: follow code copied/moved between files (for code); spec text is blamed without it, so text copied into the living spec at sync counts as written at the sync. */
function blameOf(cwd, file, copies = true) {
  const f = blameCacheFile(cwd, file, copies); const hit = f && readJsonIf(f);
  if (hit) return { perLine: hit.perLine, info: new Map(hit.info) };
  const r = blameRun(cwd, file, copies);
  if (r && f) try { fs.writeFileSync(f, JSON.stringify({ perLine: Array.from(r.perLine, (x) => x || null), info: [...r.info] })); } catch (e) { /* cache is optional */ }
  return r;
}
// Blame is the one expensive git call of a drift or finish (`-C -C` reads the whole history of the file set). Its answer depends only on
// HEAD and the file's content, so it is kept in the repository's git directory, keyed by both: a commit (new HEAD) empties the cache,
// an edit to the file changes its key. Nothing in the working tree changes.
const cacheDirs = new Map();
function blameCacheDir(cwd) {
  if (cacheDirs.has(cwd)) return cacheDirs.get(cwd);
  let dir = null;
  const gd = (git(cwd, ['rev-parse', '--absolute-git-dir']) || '').trim(); const head = (git(cwd, ['rev-parse', 'HEAD']) || '').trim();
  if (gd && head) {
    dir = path.join(gd, 'spec-blame-cache');
    try { const hf = path.join(dir, 'HEAD'); if (readIf(hf) !== head) { fs.rmSync(dir, { recursive: true, force: true }); fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(hf, head); } } catch (e) { dir = null; }
  }
  cacheDirs.set(cwd, dir); return dir;
}
function blameCacheFile(cwd, file, copies) {
  const dir = process.env.SPEC_NO_CACHE ? null : blameCacheDir(cwd); if (!dir) return null;
  let content; try { content = fs.readFileSync(path.join(cwd, file)); } catch (e) { return null; }
  return path.join(dir, require('crypto').createHash('sha1').update(`${file}\0${copies}\0`).update(content).digest('hex') + '.json');
}
function readJsonIf(f) { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { return null; } }
function blameRun(cwd, file, copies) {
  const out = git(cwd, ['blame', '-w', '-M', ...(copies ? ['-C', '-C'] : []), '--porcelain', '--', file], 256 * 1024 * 1024); if (out === null) return null;
  const perLine = []; const info = new Map(); let cur = null;
  for (const l of out.split('\n')) {
    const h = l.match(/^([0-9a-f]{40}) \d+ (\d+)/);
    if (h) { cur = h[1]; perLine[Number(h[2]) - 1] = cur; if (!info.has(cur)) info.set(cur, { sha: cur }); continue; }
    if (!cur || l.startsWith('\t')) continue;
    const t = l.match(/^committer-time (\d+)/); if (t) info.get(cur).time = Number(t[1]);
    const s = l.match(/^summary (.*)/); if (s) info.get(cur).summary = s[1];
    if (l === 'boundary') info.get(cur).boundary = true;
  }
  return { perLine, info };
}
/**
 * Units whose code changed in a commit later than the last commit that touched their requirement's text.
 * opts: { root, codeRoot, reqs: Map key -> { cap, line, file }, markers: [{key,file,line,test}] }
 * Returns { stale: [{ key, file, line, header, commit, subject, specCommit, files }], notes: [] }.
 */
function staleAnchors(o) {
  const notes = []; const stale = [];
  if (!isRepo(o.codeRoot)) return { stale, notes: ['stale-anchor skipped: the code repository has no git history'] };
  if (git(o.codeRoot, ['rev-parse', '--is-shallow-repository'])?.trim() === 'true') return { stale, notes: ['stale-anchor skipped: shallow clone (history is cut off; run `git fetch --unshallow`)'] };
  const specTop = isRepo(o.root) ? git(o.root, ['rev-parse', '--show-toplevel'])?.trim() : null;
  if (!specTop) return { stale, notes: ['stale-anchor skipped: the OpenSpec root has no git history (specs outside a repository)'] };
  if (git(o.root, ['rev-parse', '--is-shallow-repository'])?.trim() === 'true') return { stale, notes: ['stale-anchor skipped: shallow clone of the OpenSpec root'] };
  const codeTop = git(o.codeRoot, ['rev-parse', '--show-toplevel'])?.trim(); const same = fs.realpathSync(specTop) === fs.realpathSync(codeTop);
  const specBlame = new Map(); const fileBlame = new Map(); const touchedSpec = new Map(); const filesOf = new Map(); const anc = new Map();
  const specCommit = (req) => {
    if (!specBlame.has(req.file)) { const rel = path.relative(specTop, fs.realpathSync(req.file)); specBlame.set(req.file, blameOf(specTop, rel, false)); }
    const b = specBlame.get(req.file); if (!b) return null;
    const [a, z] = specRange(readIf(req.file) || '', req.line); let best = null;
    for (let i = a - 1; i < z; i++) { const sha = b.perLine[i]; if (!sha) continue; const c = b.info.get(sha); if (/^0+$/.test(sha)) return { uncommitted: true }; if (newer(c, best, specTop)) best = c; }
    return best;
  };
  const touchesSpec = (sha, cap) => {
    const k = `${sha}|${cap}`; if (touchedSpec.has(k)) return touchedSpec.get(k);
    if (!filesOf.has(sha)) filesOf.set(sha, (git(o.codeRoot, ['diff-tree', '-r', '--name-only', '--no-commit-id', '--root', sha]) || '').split('\n'));
    const names = filesOf.get(sha);
    const hit = names.some((n) => n.startsWith(`openspec/specs/${cap}/`) || new RegExp(`^openspec/changes/[^/]+/specs/${cap}/`).test(n) || new RegExp(`^openspec/changes/archive/[^/]+/specs/${cap}/`).test(n));
    touchedSpec.set(k, hit); return hit;
  };
  const isAnc = (a, b, cwd) => { const k = `${a}|${b}|${cwd || ''}`; if (!anc.has(k)) anc.set(k, spawnSync('git', ['merge-base', '--is-ancestor', a, b], { cwd: cwd || o.codeRoot }).status === 0); return anc.get(k); };
  const newer = (c, best, cwd) => !best || c.time > best.time || (c.time === best.time && isAnc(best.sha, c.sha, cwd));
  const seen = new Set(); const textOf = new Map();
  for (const m of o.markers) {
    if (m.test || isGenerated(m.file, '')) continue; const req = o.reqs.get(m.key); if (!req) continue;
    const key = `${m.key}@${m.file}`; if (seen.has(key)) continue;
    const sc = specCommit(req); if (!sc || sc.uncommitted) continue;
    if (!fileBlame.has(m.file)) fileBlame.set(m.file, blameOf(o.codeRoot, m.file));
    const fb = fileBlame.get(m.file); if (!fb) continue;
    if (!textOf.has(m.file)) textOf.set(m.file, readIf(path.join(o.codeRoot, m.file)) || '');
    const text = textOf.get(m.file); if (isGenerated(m.file, text)) continue;
    const u = analyze(text).find((x) => x.key === m.key && x.line === m.line); if (!u) continue;
    const lines = text.split('\n'); let latest = null;
    for (let i = u.start; i <= u.end; i++) {
      if (!/\S/.test(lines[i] || '') || COMMENT_LINE.test(lines[i])) continue;
      const sha = fb.perLine[i]; if (!sha || /^0+$/.test(sha)) continue;
      const c = fb.info.get(sha); if (!c || touchesSpec(sha, req.cap)) continue;
      if (newer(c, latest)) latest = c;
    }
    if (!latest) continue;
    const later = same ? (!isAnc(latest.sha, sc.sha) && (latest.time > sc.time || isAnc(sc.sha, latest.sha))) : latest.time > sc.time;
    if (!later) continue;
    seen.add(key);
    stale.push({ key: m.key, file: m.file, line: m.line, header: u.header, commit: latest.sha, subject: latest.summary || '', specCommit: sc.sha, specSubject: sc.summary || '' });
  }
  return { stale, notes };
}

