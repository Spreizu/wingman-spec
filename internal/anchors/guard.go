package anchors

import (
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/Spreizu/wingman-spec/internal/gitx"
)

var (
	generatedDir  = regexp.MustCompile(`(^|/)(generated|__generated__|vendor|vendored|third[_-]party|dist)(/|$)`)
	generatedHead = regexp.MustCompile(`(?i)@generated|DO NOT EDIT|auto-?generated|code generated by`)
)

// Sprawl: more than this many code anchors in more than this many files is spread too thin.
const (
	SprawlAnchors = 6
	SprawlFiles   = 3
)

// IsGenerated reports a generated or vendored file by its path or its first five lines.
func IsGenerated(file, text string) bool {
	if generatedDir.MatchString(file) {
		return true
	}
	head := strings.SplitN(text, "\n", 6)
	if len(head) > 5 {
		head = head[:5]
	}
	return generatedHead.MatchString(strings.Join(head, "\n"))
}

// Changed is a file changed since a base; From is the old path of a rename, "" for an untracked file.
type Changed struct{ File, From string }

// ChangedSince lists the files changed since base (committed or not, plus untracked), or nil without git.
func ChangedSince(codeRoot, base string) []Changed {
	ns, ok := gitx.RunRaw(codeRoot, nil, nil, "-c", "core.quotepath=off", "diff", "--name-status", "-M", base, "--")
	if !ok {
		return nil
	}
	var out []Changed
	seen := map[string]bool{}
	for l := range strings.SplitSeq(ns, "\n") {
		if l == "" {
			continue
		}
		p := strings.Split(l, "\t")
		if len(p) < 2 {
			continue
		}
		c := Changed{File: p[1], From: p[1]}
		if (p[0][0] == 'R' || p[0][0] == 'C') && len(p) > 2 {
			c = Changed{File: p[2], From: p[1]}
		}
		if !seen[c.File] {
			seen[c.File] = true
			out = append(out, c)
		}
	}
	for _, f := range gitx.Lines(codeRoot, "-c", "core.quotepath=off", "ls-files", "--others", "--exclude-standard") {
		if !seen[f] {
			seen[f] = true
			out = append(out, Changed{File: f})
		}
	}
	return out
}

// GuardOpts are the inputs of Guard.
type GuardOpts struct {
	CodeRoot     string
	Base         string
	Listed       map[string]bool // requirements the change mentions (delta, Spec: lines)
	Reviewed     map[string]bool // `Reviewed anchors:` keys
	ModifiedKeys map[string]bool // MODIFIED in the delta
	RemovedKeys  map[string]bool // REMOVED in the delta
	MineKeys     map[string]bool // requirements checked for sprawl (nil: all)
	ManyKeys     map[string]bool // requirements that say `Anchors: many`
	Markers      []Marker        // current markers
	IsTest       func(string) bool
	Skip         func(string) bool // spec/state files that are never code
	TaskFiles    []string
	Only         []string
}

// Finding is one anchor-guard finding.
type Finding struct {
	Kind string `json:"kind"`
	Key  string `json:"key"`
	File string `json:"file"`
	Line int    `json:"line"`
	Text string `json:"text"`
}

// GuardResult is what Guard found.
type GuardResult struct {
	Findings []Finding       `json:"findings"`
	Touched  map[string]bool `json:"-"`
	Files    []string        `json:"files"`
	Events   []Event         `json:"events"`
}

func show(codeRoot, base, file string) (string, bool) {
	return gitx.RunRaw(codeRoot, nil, nil, "show", base+":"+file)
}

// Guard compares the anchored code against a base: anchored code touched without the change naming its requirement,
// a modified requirement whose code did not change, anchors removed or moved, sprawl, anchors outside the task's files.
func Guard(o GuardOpts) GuardResult {
	var code []Marker
	for _, m := range o.Markers {
		if !m.Test && !IsGenerated(m.File, "") {
			code = append(code, m)
		}
	}
	var events []Event
	if o.Base != "" {
		for _, c := range ChangedSince(o.CodeRoot, o.Base) {
			if o.Only != nil && !slices.Contains(o.Only, c.File) {
				continue
			}
			if (o.IsTest != nil && o.IsTest(c.File)) || (o.Skip != nil && o.Skip(c.File)) || generatedDir.MatchString(c.File) {
				continue
			}
			baseText := ""
			if c.From != "" {
				baseText, _ = show(o.CodeRoot, o.Base, c.From)
			}
			b, _ := os.ReadFile(filepath.Join(o.CodeRoot, c.File))
			curText := string(b)
			if strings.Contains(baseText, "\x00") || strings.Contains(curText, "\x00") {
				continue
			}
			probe := curText
			if probe == "" {
				probe = baseText
			}
			if IsGenerated(c.File, probe) {
				continue
			}
			if !strings.Contains(baseText, "@spec") && !strings.Contains(curText, "@spec") {
				continue
			}
			var cc []string
			for l := range strings.SplitSeq(curText, "\n") {
				if !blank(l) && !commentLine.MatchString(l) {
					if n := NormLine(l); n != "" {
						cc = append(cc, n)
					}
				}
			}
			curCode := strings.Join(cc, "\n")
			for _, e := range Compare(baseText, curText) {
				e.File = c.File
				e.MarkerOnly = e.Kind == "removed" && e.Body != "" && strings.Contains(curCode, e.Body)
				events = append(events, e)
			}
		}
	}
	// a unit that left one file and appeared in another: unchanged text = moved, different text = moved and edited
	dropped := map[int]bool{}
	for i := range events {
		if events[i].Kind != "added" {
			continue
		}
		j := -1
		for x := range events {
			if !dropped[x] && events[x].Kind == "removed" && events[x].Key == events[i].Key {
				j = x
				break
			}
		}
		if j < 0 {
			continue
		}
		dropped[j] = true
		if events[i].Body == events[j].Body {
			events[i].Kind, events[i].From = "moved", events[j].File
		} else {
			events[i].Kind, events[i].MovedFrom = "modified", events[j].File
		}
	}
	kept := events[:0:0]
	for i, e := range events {
		if !dropped[i] {
			kept = append(kept, e)
		}
	}
	events = kept
	return guardFinish(o, code, events)
}

// guardFinish turns the diff events into findings. It owns the result, so every finding lands in what it returns.
func guardFinish(o GuardOpts, code []Marker, events []Event) GuardResult {
	res := GuardResult{Findings: []Finding{}, Touched: map[string]bool{}, Files: []string{}, Events: []Event{}}
	add := func(kind, key, file string, line int, text string) {
		res.Findings = append(res.Findings, Finding{kind, key, file, line, text})
	}
	stillAnchored := func(key string) (Marker, bool) {
		for _, m := range code {
			if m.Key == key {
				return m, true
			}
		}
		return Marker{}, false
	}
	seenFile := map[string]bool{}
	for _, e := range events {
		if !seenFile[e.File] {
			seenFile[e.File] = true
			res.Files = append(res.Files, e.File)
		}
		if e.Kind == "modified" || e.Kind == "added" {
			res.Touched[e.Key] = true
		}
	}
	known := func(k string) bool { return o.Listed[k] || o.Reviewed[k] }
	for _, e := range events {
		where := e.File + ":" + strconv.Itoa(e.Line)
		unit := ""
		if e.Header != "" {
			unit = " (`" + cutRunes(e.Header, 80) + "`)"
		}
		if (e.Kind == "modified" || e.Kind == "added") && !known(e.Key) {
			rename := ""
			if e.Renamed {
				rename = " It was renamed or its signature changed."
			}
			what := "was modified"
			if e.Kind == "added" {
				what = "got a new anchor"
			}
			add("anchor-touched-unlisted", e.Key, e.File, e.Line, where+": code anchored to `"+e.Key+"`"+unit+" "+what+", but this change does not mention that requirement (no delta, no `Spec:` line)."+rename+" Update the requirement and its scenarios (delta spec), or confirm it still holds with a line `Reviewed anchors: "+e.Key+" - <why it still holds>` in tasks.md or progress.md.")
		}
		if e.Kind == "moved" && !known(e.Key) {
			add("anchor-moved", e.Key, e.File, e.Line, where+": the anchored unit of `"+e.Key+"`"+unit+" moved here from "+e.From+" unchanged. Confirm the anchor still belongs where it is now (and that the requirement does not describe the old place).")
		}
		if e.Kind == "removed" && !o.RemovedKeys[e.Key] {
			m, still := stillAnchored(e.Key)
			switch {
			case still && e.MarkerOnly:
			case still:
				if !known(e.Key) {
					add("anchor-moved", e.Key, e.File, e.Line, where+": the anchored unit of `"+e.Key+"`"+unit+" left this file; the requirement is still anchored in "+m.File+". Confirm the anchor still belongs where it is now.")
				}
			case !o.Reviewed[e.Key]:
				add("anchor-removed", e.Key, e.File, e.Line, where+": the anchored unit of `"+e.Key+"`"+unit+" was removed or lost its marker and the requirement has no code anchor now. Restore or re-anchor it, or retire the requirement in a delta (REMOVED).")
			}
		}
	}
	mod := make([]string, 0, len(o.ModifiedKeys))
	for k := range o.ModifiedKeys {
		mod = append(mod, k)
	}
	slices.Sort(mod)
	for _, k := range mod {
		m, still := stillAnchored(k)
		if o.Reviewed[k] || res.Touched[k] || !still {
			continue
		}
		add("requirement-changed-code-untouched", k, m.File, m.Line, m.File+":"+strconv.Itoa(m.Line)+": requirement `"+k+"` is modified by the delta spec but none of the code anchored to it changed. Change the code, or add `Reviewed anchors: "+k+" - <why the code already satisfies the new text>`.")
	}
	type spread struct {
		n     int
		files []string
	}
	per := map[string]*spread{}
	var order []string
	for _, m := range code {
		if (o.MineKeys != nil && !o.MineKeys[m.Key]) || o.ManyKeys[m.Key] {
			continue
		}
		p := per[m.Key]
		if p == nil {
			p = &spread{}
			per[m.Key] = p
			order = append(order, m.Key)
		}
		p.n++
		if !slices.Contains(p.files, m.File) {
			p.files = append(p.files, m.File)
		}
	}
	for _, k := range order {
		p := per[k]
		if p.n > SprawlAnchors && len(p.files) > SprawlFiles {
			add("anchor-sprawl", k, p.files[0], 0, "`"+k+"` has "+strconv.Itoa(p.n)+" code anchors in "+strconv.Itoa(len(p.files))+" files (more than "+strconv.Itoa(SprawlAnchors)+" anchors in more than "+strconv.Itoa(SprawlFiles)+" files): spread too thin to mean anything. Anchor the entry point (the function that starts the behaviour) and let the tests cover the rest.")
		}
	}
	if len(o.TaskFiles) > 0 {
		seen := map[string]bool{}
		for _, e := range events {
			if (e.Kind == "modified" || e.Kind == "added") && !InFiles(o.TaskFiles, e.File) && !seen[e.File] {
				seen[e.File] = true
				what := "changed"
				if e.Kind == "added" {
					what = "added"
				}
				add("anchor-outside-task-files", e.Key, e.File, e.Line, e.File+":"+strconv.Itoa(e.Line)+": a `@spec` anchor was "+what+" in a file this task's `Files:` line does not list. Either the plan missed this file (name it) or the anchor is misplaced.")
			}
		}
	}
	res.Events = events
	if res.Events == nil {
		res.Events = []Event{}
	}
	return res
}

// InFiles reports whether f matches one of the patterns of a task's Files: line (exact, a directory, or a * / ** glob).
func InFiles(patterns []string, f string) bool {
	for _, p := range patterns {
		if p == f || (strings.HasSuffix(p, "/") && strings.HasPrefix(f, p)) || strings.HasPrefix(f, strings.TrimSuffix(p, "/")+"/") {
			return true
		}
		if strings.Contains(p, "*") && GlobRE(p).MatchString(f) {
			return true
		}
	}
	return false
}

// GlobRE compiles a * / ** path glob.
func GlobRE(p string) *regexp.Regexp {
	var b strings.Builder
	b.WriteString("^")
	for i := 0; i < len(p); i++ {
		switch {
		case strings.HasPrefix(p[i:], "**"):
			b.WriteString(".*")
			i++
		case p[i] == '*':
			b.WriteString("[^/]*")
		default:
			b.WriteString(regexp.QuoteMeta(p[i : i+1]))
		}
	}
	b.WriteString("$")
	return regexp.MustCompile(b.String())
}

func cutRunes(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n])
}
