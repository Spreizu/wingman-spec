#!/usr/bin/env node
// Bundles the visual helper (visual/wingman-visual.cjs and visual/lib) into one ES module that the CLI embeds
// (internal/visual/bundle/wingman-visual.mjs, go:embed) and writes to <code root>/.wingman-spec/bin on first use.
// Playwright and axe-core stay outside: the helper loads them from the project at run time.
// Usage: node scripts/build-visual.mjs [--check]   (--check: exit 1 when the committed bundle is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// esbuild: the extension's dev dependency (vscode-extension/node_modules), or ESBUILD_PATH (a directory holding the package).
function loadEsbuild() {
  for (const from of [process.env.ESBUILD_PATH && join(process.env.ESBUILD_PATH, 'x.js'), join(root, 'vscode-extension', 'package.json'), import.meta.url].filter(Boolean)) {
    try { return createRequire(from)('esbuild'); } catch { /* next */ }
  }
  console.error('esbuild not found: run pnpm install in vscode-extension, or set ESBUILD_PATH'); process.exit(2);
}
const { build } = loadEsbuild();
const out = join(root, 'internal', 'visual', 'bundle', 'wingman-visual.mjs');
const banner = [
  '// Generated by scripts/build-visual.mjs from visual/: do not edit.',
  "import { createRequire as __wmCreateRequire } from 'node:module';",
  "import { fileURLToPath as __wmFileURLToPath } from 'node:url';",
  "import { dirname as __wmDirname } from 'node:path';",
  'const require = __wmCreateRequire(import.meta.url);',
  'const __filename = __wmFileURLToPath(import.meta.url);',
  'const __dirname = __wmDirname(__filename);',
].join('\n');
const res = await build({
  entryPoints: [join(root, 'visual', 'wingman-visual.cjs')],
  bundle: true, platform: 'node', format: 'esm', target: 'node18', write: false, legalComments: 'none',
  external: ['playwright', 'playwright-core', '@playwright/test', 'axe-core'], banner: { js: banner }, logLevel: 'warning',
});
const code = res.outputFiles[0].text;
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== code) { console.error(`${out} is out of date: run node scripts/build-visual.mjs`); process.exit(1); }
  console.log('visual bundle up to date');
} else {
  writeFileSync(out, code);
  console.log(`wrote ${out} (${(code.length / 1024).toFixed(0)} KB)`);
}
