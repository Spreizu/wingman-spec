#!/usr/bin/env bash
# render-harness.sh - generate one harness's commands and subagent from the single source in
# project-template/harness/ (commands/*.md, agents/*.md, partials/*.md).
#
# Usage: scripts/render-harness.sh <cursor|claude|codex> <out-dir>
#   Writes files under <out-dir> and prints each written path relative to it. Pure function of the
#   source: same input, byte-identical output. install.sh renders into a temp dir, then copies.
#
# The generated-by note is never the first line (Cursor and Claude Code derive a command's description from the
# front matter / first line): front matter with `description:` comes first, the note after it.
#
# Source format: YAML front matter (`description:`, optional `argument-hint:`; agents also `name:`),
# then a harness-neutral Markdown body. A line `{{> name}}` is replaced by partials/name.md.
#
#   harness  commands                                  subagent
#   cursor   .cursor/commands/<n>.md   (description)    .cursor/agents/<a>.md   (name, description, model: inherit)
#   claude   .claude/commands/<n>.md   (front matter)   .claude/agents/<a>.md   (name, description)
#   codex    .agents/skills/<n>/SKILL.md (name, desc;   .codex/agents/<a>.toml  (name, description, developer_instructions)
#            Codex has no project slash commands, so each command is a skill invoked as $<n>)
# An agent with `readonly: true` (spec-visual-reviewer) gets `readonly: true` in Cursor, `[features] shell_tool = false`
# in Codex (custom agent files cannot set a sandbox; view_image stays on) and `tools: Read, Grep, Glob`
# in Claude Code; Codex agent files cannot restrict tools (the sandbox is inherited), so its body says "do not edit".
set -euo pipefail

HARNESS="${1:-}"; OUT="${2:-}"
SRC="$(cd "$(dirname "$0")/.." && pwd)/project-template/harness"
case "$HARNESS" in cursor|claude|codex) ;; *) echo "usage: render-harness.sh <cursor|claude|codex> <out-dir>" >&2; exit 2 ;; esac
[ -n "$OUT" ] || { echo "render-harness: missing <out-dir>" >&2; exit 2; }
MARK="generated by the wingman-spec install.sh from harness/"

# front matter value: fm <file> <key>   (strips surrounding double quotes)
fm() { awk -v k="$2" 'NR==1 && $0=="---" {f=1; next} f && $0=="---" {exit} f && index($0, k ": ")==1 { v=substr($0, length(k)+3); gsub(/^"|"$/, "", v); print v; exit }' "$1"; }
# body with partials expanded
body() {
  awk -v dir="$SRC/partials" '
    NR==1 && $0=="---" { fmz=1; next }
    fmz { if ($0=="---") fmz=0; next }
    /^\{\{> [a-z0-9-]+\}\}$/ { n=$0; gsub(/^\{\{> |\}\}$/, "", n); f=dir "/" n ".md"; ok=0
      while ((getline l < f) > 0) { print l; ok=1 } close(f)
      if (!ok) { print "render-harness: missing partial " f > "/dev/stderr"; exit 3 } next }
    { print }' "$1"
}
# Codex invokes skills as $name instead of /name.
codexify() { sed -E 's#(^|[[:space:](`"'"'"'])/(spec-[a-z]+)#\1$\2#g'; }
emit() { mkdir -p "$(dirname "$OUT/$1")"; cat > "$OUT/$1"; echo "$1"; }

for src in "$SRC"/commands/*.md; do
  n="$(basename "$src" .md)"; d="$(fm "$src" description)"; h="$(fm "$src" argument-hint)"
  [ -n "$d" ] || { echo "render-harness: $src has no description" >&2; exit 3; }
  note="<!-- $MARK""commands/$n.md; edits are overwritten on reinstall -->"
  # shellcheck disable=SC2016 # the codex branch prints a literal `$name` for the user
  case "$HARNESS" in
    cursor) { printf -- '---\ndescription: "%s"\n---\n%s\n' "$d" "$note"; body "$src"; } | emit ".cursor/commands/$n.md" ;;
    claude) { printf -- '---\ndescription: "%s"\n' "$d"; [ -z "$h" ] || printf 'argument-hint: "%s"\n' "$h"; printf -- '---\n%s\n' "$note"; body "$src"; } | emit ".claude/commands/$n.md" ;;
    codex)  { printf -- '---\nname: %s\ndescription: "%s"\n---\n%s\n' "$n" "$d" "$note"; [ -z "$h" ] || printf 'Invoke as `$%s %s`.\n\n' "$n" "$h"; body "$src" | codexify; } | emit ".agents/skills/$n/SKILL.md" ;;
  esac
done

for src in "$SRC"/agents/*.md; do
  a="$(fm "$src" name)"; d="$(fm "$src" description)"; ro="$(fm "$src" readonly)"
  [ -n "$a" ] && [ -n "$d" ] || { echo "render-harness: $src needs name and description" >&2; exit 3; }
  note="<!-- $MARK""agents/$a.md; edits are overwritten on reinstall -->"
  case "$HARNESS" in
    cursor) { printf -- '---\nname: %s\ndescription: "%s"\nmodel: inherit\n' "$a" "$d"; [ "$ro" != true ] || printf 'readonly: true\n'; printf -- '---\n%s\n' "$note"; body "$src"; } | emit ".cursor/agents/$a.md" ;;
    claude) { printf -- '---\nname: %s\ndescription: "%s"\n' "$a" "$d"; [ "$ro" != true ] || printf 'tools: Read, Grep, Glob\n'; printf -- '---\n%s\n' "$note"; body "$src"; } | emit ".claude/agents/$a.md" ;;
    codex)
      b="$(body "$src" | codexify)"
      case "$b" in *"'''"*) echo "render-harness: $src body contains ''' and cannot be a TOML literal string" >&2; exit 3 ;; esac
      { printf 'name = "%s"\ndescription = "%s"\n# %s%s; edits are overwritten on reinstall\n' "$a" "$(printf '%s' "$d" | codexify)" "$MARK" "agents/$a.md"
        printf "developer_instructions = '''\n%s\n'''\n" "$b"
        [ "$ro" != true ] || printf '\n[features]\nshell_tool = false\n'; } | emit ".codex/agents/$a.toml" ;;
  esac
done
